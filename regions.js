// 한글 → 로마자 (국어의 로마자 표기법, 음운 변화는 생략한 간이 변환)
const HG_INITIAL = ["g","kk","n","d","tt","r","m","b","pp","s","ss","","j","jj","ch","k","t","p","h"];
const HG_MEDIAL = ["a","ae","ya","yae","eo","e","yeo","ye","o","wa","wae","oe","yo","u","wo","we","wi","yu","eu","ui","i"];
const HG_FINAL = ["","k","k","k","n","n","n","t","l","k","m","l","l","l","p","l","m","p","p","t","t","ng","t","t","k","t","p","t"];

function romanizeHangul(text) {
  let out = "";
  for (const ch of text) {
    const code = ch.charCodeAt(0) - 0xac00;
    if (code < 0 || code > 11171) { out += ch; continue; }
    out += HG_INITIAL[Math.floor(code / 588)]
         + HG_MEDIAL[Math.floor((code % 588) / 28)]
         + HG_FINAL[code % 28];
  }
  return out;
}

const hasHangul = (s) => /[ㄱ-ㆎ가-힣]/.test(s);

// "제주도" → "제주", "수원시" → "수원" 처럼 행정구역 접미사 제거
function stripSuffix(s) {
  return s.replace(/(특별자치도|특별자치시|특별시|광역시|도|시|군|구)$/, "");
}
